-- Run once in the Neon SQL Editor for the selected project/branch/database.
-- This creates the PostgreSQL version of the enrollment schema without deleting data.

CREATE TABLE IF NOT EXISTS users (
  access_id VARCHAR(50) PRIMARY KEY,
  full_name VARCHAR(100) NOT NULL,
  course VARCHAR(50) NOT NULL,
  year_level INTEGER NOT NULL,
  age INTEGER NOT NULL,
  email VARCHAR(100),
  location VARCHAR(100) DEFAULT 'Iloilo Sector',
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS subjects (
  code VARCHAR(20) PRIMARY KEY,
  description VARCHAR(160) NOT NULL,
  units SMALLINT NOT NULL CHECK (units >= 0),
  schedule VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS enrollments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_access_id VARCHAR(50) NOT NULL REFERENCES users(access_id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  total_units SMALLINT NOT NULL,
  total_amount NUMERIC(10,2) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_enrollments_student ON enrollments(student_access_id);

CREATE TABLE IF NOT EXISTS enrollment_subjects (
  enrollment_id BIGINT NOT NULL REFERENCES enrollments(id)
    ON UPDATE CASCADE ON DELETE CASCADE,
  subject_code VARCHAR(20) NOT NULL REFERENCES subjects(code)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  PRIMARY KEY (enrollment_id, subject_code)
);

CREATE TABLE IF NOT EXISTS student_photos (
  student_access_id VARCHAR(50) PRIMARY KEY REFERENCES users(access_id)
    ON UPDATE CASCADE ON DELETE CASCADE,
  mime_type VARCHAR(30) NOT NULL,
  image_data BYTEA NOT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

